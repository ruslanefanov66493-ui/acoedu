/**
 * Public phone / email / address. Empty until the owner fills aco_legal_context().
 */
function aco_the_public_contacts( $layout = 'footer' ) {
    $ctx   = aco_legal_context();
    $cls   = $layout === 'footer' ? ' class="lh-footer__link"' : '';
    $items = [];
    if ( $ctx['phone'] ) {
        $tel     = preg_replace( '/\D+/', '', $ctx['phone'] );
        $items[] = [ 'label' => 'Телефон', 'html' => '<a' . $cls . ' href="tel:+' . esc_attr( $tel ) . '">' . esc_html( $ctx['phone'] ) . '</a>' ];
    }
    if ( $ctx['email'] ) {
        $items[] = [ 'label' => 'Email', 'html' => '<a' . $cls . ' href="mailto:' . esc_attr( $ctx['email'] ) . '">' . esc_html( $ctx['email'] ) . '</a>' ];
    }
    if ( $ctx['address'] ) {
        $items[] = [ 'label' => 'Адрес', 'html' => '<span' . $cls . '>' . esc_html( $ctx['address'] ) . '</span>' ];
    }

    if ( ! $items ) {
        if ( $layout === 'footer' ) {
            echo '<a class="lh-footer__link" href="' . esc_url( aco_contacts_page_url() ) . '">Написать через форму</a>';
        }
        return;
    }

    foreach ( $items as $item ) {
        if ( $layout === 'details' ) {
            echo '<div class="lh-contacts-detail"><span class="lh-contacts-detail__label">' . esc_html( $item['label'] ) . '</span>' . $item['html'] . '</div>';
        } elseif ( $layout === 'list' ) {
            echo '<li>' . $item['html'] . '</li>';
        } else {
            echo $item['html'];
        }
    }
}


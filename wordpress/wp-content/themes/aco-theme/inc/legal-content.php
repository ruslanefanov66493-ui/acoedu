function aco_ensure_legal_pages() {
    if ( get_option( 'aco_legal_pages_v2' ) ) {
        return;
    }

    $pages = [
        'oferta'        => 'Публичная оферта',
        'privacy'       => 'Политика конфиденциальности',
        'personal-data' => 'Обработка персональных данных',
        'refund'        => 'Возврат средств',
        'cookies'       => 'Политика использования файлов cookies',
        'how'           => 'Как получить курс',
    ];

    foreach ( $pages as $slug => $title ) {
        $exists = get_page_by_path( $slug );
        if ( $exists ) {
            continue;
        }
        wp_insert_post( [
            'post_type'   => 'page',
            'post_status' => 'publish',
            'post_title'  => $title,
            'post_name'   => $slug,
            'post_content'=> '',
        ], true );
    }

    update_option( 'aco_legal_pages_v2', 1 );
}
add_action( 'init', 'aco_ensure_legal_pages' );

